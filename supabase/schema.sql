-- ==========================================================
-- Supabase Schema untuk ESP32 IoT Monitoring Dashboard
-- ==========================================================

-- 1. Membuat tabel sensor_readings
CREATE TABLE IF NOT EXISTS public.sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    suhu NUMERIC(5, 2) NOT NULL,
    kelembapan NUMERIC(5, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

-- Memberikan komentar pada kolom tabel
COMMENT ON TABLE public.sensor_readings IS 'Penyimpanan data sensor suhu dan kelembapan dari ESP32';
COMMENT ON COLUMN public.sensor_readings.suhu IS 'Nilai suhu dalam derajat Celsius (°C)';
COMMENT ON COLUMN public.sensor_readings.kelembapan IS 'Nilai kelembapan udara dalam persen (%)';
COMMENT ON COLUMN public.sensor_readings.created_at IS 'Waktu data diterima oleh Supabase';

-- 2. Membuat Index untuk performa query data terbaru
CREATE INDEX IF NOT EXISTS idx_sensor_readings_created_at_desc 
ON public.sensor_readings (created_at DESC);

-- 3. Mengaktifkan Row Level Security (RLS)
ALTER TABLE public.sensor_readings ENABLE ROW LEVEL SECURITY;

-- Policy: Izinkan publik/anon untuk membaca data (SELECT)
CREATE POLICY "Allow public read access"
ON public.sensor_readings
FOR SELECT
TO anon, authenticated
USING (true);

-- Policy: Izinkan ESP32 / anon untuk menyisipkan data baru (INSERT)
CREATE POLICY "Allow public insert access"
ON public.sensor_readings
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 4. Mengaktifkan Supabase Realtime untuk tabel sensor_readings
-- (Dibutuhkan agar perubahan data langsung dipancarkan via WebSocket ke dashboard)
ALTER PUBLICATION supabase_realtime ADD TABLE public.sensor_readings;

